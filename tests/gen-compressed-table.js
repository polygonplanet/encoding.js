/**
 * Generate the compressed conversion tables in src/ from the readable
 * source tables in tests/
 *
 * Usage:
 *   node tests/gen-compressed-table.js
 */
/* eslint-disable no-console */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const TABLES = [
  {
    src: 'tests/utf8-to-jis-table.js',
    dst: 'src/utf8-to-jis-table.js',
    docComment: `/**
 * Encoding conversion table for UTF-8 to JIS (JIS X 0208)
 *
 * The table is stored in a compressed form and is expanded by
 * src/encoding-table.js on first use.
 *
 * Uncompressed version: tests/utf8-to-jis-table.js
 * Generated by: tests/gen-compressed-table.js
 */`
  },
  {
    src: 'tests/utf8-to-jisx0212-table.js',
    dst: 'src/utf8-to-jisx0212-table.js',
    docComment: `/**
 * Encoding conversion table for UTF-8 to JIS X 0212:1990 (Hojo-Kanji)
 *
 * The table is stored in a compressed form and is expanded by
 * src/encoding-table.js on first use.
 *
 * Uncompressed version: tests/utf8-to-jisx0212-table.js
 * Generated by: tests/gen-compressed-table.js
 *
 * Character mappings based on:
 * https://www.unicode.org/Public/MAPPINGS/OBSOLETE/EASTASIA/JIS/JIS0212.TXT
 */`
  }
];

const hex = (n) => n.toString(16);

// UTF-8 -> Unicode code point
// Same as UTF8ToUNICODE, but takes UTF-8 bytes packed into a number
// and handles only 1-3 bytes
function utf8ToUnicode(utf8) {
  utf8 |= 0;
  if (utf8 < 0x80) {
    return utf8;
  }
  if (utf8 < 0x10000) {
    return ((utf8 >> 8) & 0x1F) << 6 | (utf8 & 0x3F);
  }
  return ((utf8 >> 16) & 0x0F) << 12 | ((utf8 >> 8) & 0x3F) << 6 | (utf8 & 0x3F);
}

function generate(spec) {
  // srcTable = { UTF-8 : JIS } (e.g., { ..., 0xE28096: 0x2142, 0xEFBD9C: 0x2143, ... })
  const srcTable = require(path.resolve(ROOT, spec.src));
  const utf8Keys = Object.keys(srcTable).map(Number);

  // Group UTF-8 keys by JIS code
  // jisToUtf8Keys = { JIS : [UTF-8, ...] } (e.g., { 0x2142: [0xE28096, 0xE288A5], ... })
  const jisToUtf8Keys = {};
  utf8Keys.forEach((key) => {
    const jis = srcTable[key];
    (jisToUtf8Keys[jis] = jisToUtf8Keys[jis] || []).push(key);
  });

  const jisCodes = Object.keys(jisToUtf8Keys).map(Number).sort((a, b) => a - b);

  const lines = [];
  let tokens = null;
  let lead = -1;
  let trail = 0;
  // Run length encoding: { cp: start code point, n: run length }
  let run = null;

  const flushRun = () => {
    if (run) {
      tokens.push(`${hex(run.cp)}${run.n > 1 ? '+' + run.n : ''}`);
      run = null;
    }
  };

  jisCodes.forEach((jis) => {
    // Half-width katakana are generated by formula in src/encoding-table.js
    if (jis <= 0x5F) {
      return;
    }

    // Keep the largest UTF-8 key (the one the reverse table returns).
    // The others are in src/utf8-to-jis-alias-table.js
    const cp = utf8ToUnicode(Math.max(...jisToUtf8Keys[jis]));
    const jisLead = jis >> 8;
    const jisTrail = jis & 0xFF;

    if (jisLead !== lead) {
      flushRun();
      lead = jisLead;
      trail = 0x21;
      tokens = [`${hex(lead)}=`];
      lines.push(tokens);
    }

    if (jisTrail > trail) {
      flushRun();
      tokens.push(`-${jisTrail - trail}`);
      trail = jisTrail;
    }

    if (run && run.cp + run.n === cp) {
      run.n++;
    } else {
      flushRun();
      run = { cp, n: 1 };
    }
    trail++;
  });
  flushRun();

  const texts = lines.map((lineTokens) => lineTokens[0] + lineTokens.slice(1).join(','));
  const out = [
    spec.docComment,
    'module.exports = [',
    texts.map((text, i) => `  '${text}'${i < texts.length - 1 ? ',' : ''}`).join('\n'),
    `].join(',');`,
    ''
  ].join('\n');

  fs.writeFileSync(path.join(ROOT, spec.dst), out);
  console.log(`${spec.dst}: done.`);
}

TABLES.forEach(generate);
